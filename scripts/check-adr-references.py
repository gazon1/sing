#!/usr/bin/env python3
"""check_adr_references.py — find references to ADRs that no longer exist.

Why this exists (2026-10-05): Phase 2 of the spec-governance sweep archives and
deletes ADRs. Nothing in the repo verified that a deleted ADR was not still cited,
so deletions silently broke documentation links. `check-doc-dead-refs.py` does not
cover this case: it checks *file paths* that do not exist, not dated ADR slugs that
were referenced by bare token (e.g. `2026-09-27-di-module-aggregator-narrative` in
prose, without `.md`).

This is the gate that makes ADR deletion safe. A token shaped like a dated ADR slug
that resolves to no file in docs/decisions/ (including archive/) is an error,
reported with file and line.

Known false positives, seeded into the baseline rather than hidden in code:
  - regex/prefix artifacts such as `2026-09-16-nav3-type-asymmetry-adr`
  - skill slugs that were renamed, which read exactly like ADR slugs
  - ADRs legitimately cited in a historical/superseded note

Usage:
  python3 scripts/check-adr-references.py
  python3 scripts/check-adr-references.py --update-baseline
"""

from __future__ import annotations

import click
import pathlib
import re
import sys

# This script must resolve `sgate` against *this* checkout: an editable
# install of a sibling worktree is a different tree under the same name.
_SCRIPTS_SRC = str(pathlib.Path(__file__).resolve().parent / 'src')
if _SCRIPTS_SRC not in sys.path:
    sys.path.insert(0, _SCRIPTS_SRC)

from sgate.commands.base import run

CLEAN = 0
VALIDATION_FAILURE = 1
IO_ERROR = 2

ROOT = pathlib.Path(__file__).resolve().parent.parent
DECISIONS_DIR = ROOT / 'docs' / 'decisions'
PLANS_DIR = ROOT / 'docs' / 'plans'
BASELINE = ROOT / 'config' / 'docs' / 'adr-refs-baseline.txt'

# A dated ADR slug: YYYY-MM-DD-<kebab-slug>. The trailing group must contain at least
# one letter, so a bare date (2026-10-05) is not treated as a reference.
TOKEN_RE = re.compile(r'\b(\d{4}-\d{2}-\d{2}-[a-z0-9]+(?:-[a-z0-9]+)+)\b')

#: A path into the openspec corpus.
#:
#: The archive's directories carry the date of the change they hold
#: (`openspec/changes/archive/2026-10-20-<slug>/`), so a path into the corpus
#: looks like a dated ADR slug and is not one. A citation of a decision is a
#: slug that stands on its own; a path into a directory of changes is a
#: pointer to a change, and the gate that checks those is
#: `check-review-verdicts.py`.
CHANGE_PATH_RE = re.compile(r'openspec/changes/\S*')

# Files an agent actually reads. Kept explicit so adding a doc source is a decision.
SCAN_FILES = [
    ROOT / 'AGENTS.md',
    ROOT / 'ARCHITECTURE.md',
    ROOT / 'README.md',
    ROOT / 'PROGRESS.md',
    ROOT / 'CLAUDE.md',
]
SCAN_GLOBS = [
    'docs/**/*.md',
    '.agents/skills/**/*.md',
    'openspec/**/*.md',
    'config/**/*.md',
]

# Never scan generated/derived trees: they restate other files and would double-count.
# DIGEST.md and DIGEST-full.md are generated by refresh-decisions-digest.py and are
# gitignored, so their citations are a copy of findings that are checked at their source.
# DIGEST-full.md was added here on 2026-10-15 when the digest split in two; without it the
# full index reported two dangling citations that live in an ADR body and are checked there.
EXCLUDE_PARTS = {'node_modules', '.git', 'build', 'target', 'archive'}
EXCLUDE_FILES = {'DIGEST.md', 'DIGEST-full.md', 'SKILLS-CATALOG.md'}


def existing_slugs() -> set[str]:
    """Every dated doc slug that exists, in docs/decisions/ and docs/plans/.

    Resolving against docs/decisions/ alone made six false positives out of ten
    findings on 2026-10-05: `docs/plans/2026-10-04-mr6-retro-gate.md` and
    `docs/plans/2026-10-03-agenda-views-test-plan.md` are real files, cited by
    path, and the gate reported their dates as dangling ADR slugs.

    The gate's job is "a reference to a dated decision document that no longer
    exists", and a dated file that is present is not that — whatever directory
    it lives in. Baseline is for genuine exceptions, not for a lookup that was
    pointed at the wrong directory.
    """
    slugs: set[str] = set()
    for directory in (DECISIONS_DIR, PLANS_DIR):
        if not directory.is_dir():
            continue
        for path in directory.rglob('*.md'):
            name = path.stem
            if re.match(r'^\d{4}-\d{2}-\d{2}-', name):
                slugs.add(name)
    return slugs


def iter_sources() -> list[pathlib.Path]:
    files: list[pathlib.Path] = [f for f in SCAN_FILES if f.is_file()]
    for pattern in SCAN_GLOBS:
        for path in ROOT.glob(pattern):
            if not path.is_file():
                continue
            if any(part in EXCLUDE_PARTS for part in path.parts):
                continue
            if path.name in EXCLUDE_FILES:
                continue
            files.append(path)
    return sorted(set(files))


def find_dangling(slugs: set[str]) -> list[str]:
    """Return 'file:token' for every dated-ADR token with no matching file.

    Deliberately not keyed by line number. A line-keyed baseline breaks the moment an
    unrelated edit shifts a line, which turns a baselined exception into a spurious
    failure — the gate then gets ignored rather than fixed. A token reference is a
    property of the sentence, not of its position.
    """
    dangling: list[str] = []
    for path in iter_sources():
        try:
            text = path.read_text()
            rel = path.relative_to(ROOT)
        except (UnicodeDecodeError, OSError):
            # Unreadable file: nothing to scan, and not a finding.
            continue
        except ValueError:
            # A scanned path outside ROOT would make relative_to raise. Report it
            # rather than swallowing it, which previously made the gate silently
            # return zero findings for any ROOT/source mismatch.
            click.echo(
                f'ERROR: {path} is outside ROOT ({ROOT}); fix SCAN_FILES/SCAN_GLOBS',
                err=True,
            )
            continue
        seen: set[str] = set()
        for line in text.splitlines():
            for match in TOKEN_RE.finditer(line):
                token = match.group(1)
                if any(
                    path.start() <= match.start() and match.end() <= path.end()
                    for path in CHANGE_PATH_RE.finditer(line)
                ):
                    # A directory of changes, not a citation of a decision.
                    continue
                # Tolerate an explicit .md suffix and a docs/decisions/ prefix.
                token = token.removesuffix('.md')
                if token in slugs:
                    continue
                key = f'{rel}:{token}'
                if key not in seen:
                    seen.add(key)
                    dangling.append(key)
    return sorted(dangling)


def cited_slugs(slugs: set[str]) -> set[str]:
    """Which of `slugs` are actually referenced from outside the decision corpus.

    The inverse question of `find_dangling`: that one asks "which references have no
    file", this one asks "which files have no reference". Same traversal, same
    `iter_sources()` — so a citation counted here is exactly a citation the dangling
    scan would have looked at, and the two cannot drift apart.

    `adr prune` (#525) needs the answer, and it needs it from *this* traversal. A
    second implementation of "where does a citation live" would be the exact failure
    this gate was written to prevent.
    """
    cited: set[str] = set()
    for path in iter_sources():
        try:
            text = path.read_text()
        except (UnicodeDecodeError, OSError):
            continue
        for line in text.splitlines():
            for match in TOKEN_RE.finditer(line):
                token = match.group(1).removesuffix('.md')
                if token in slugs:
                    cited.add(token)
    return cited


@click.command()
@click.option('--update-baseline', is_flag=True,
              help='rewrite the baseline from current findings, then exit')
@click.option('--baseline', default=str(BASELINE),
              help='path to the baseline file')
@click.option('--list-cited', is_flag=True,
              help='print every cited slug, one per line, then exit (for `adr prune`)')
@click.pass_context
def cli(ctx: click.Context, update_baseline: bool, baseline: str, list_cited: bool) -> None:
    slugs = existing_slugs()
    if not slugs:
        raise ctx.exit(
            f'check_adr_references.py: no ADRs found under {DECISIONS_DIR}'
        )

    if list_cited:
        for slug in sorted(cited_slugs(slugs)):
            click.echo(slug)
        raise ctx.exit(CLEAN)

    dangling = find_dangling(slugs)
    # Sorted before any write. `find_dangling` returns in scan order, which walks
    # the file list, so two runs over the same tree could reorder every line and
    # turn a maintenance command into a diff nobody can read. A baseline whose
    # ordering is unstable cannot be reviewed as a change.
    dangling = sorted(dangling)

    if update_baseline:
        header = (
            '# Accepted dangling ADR references.\n'
            '#\n'
            '# Each line is <file>:<token>. A token is a dated ADR slug that no\n'
            '# longer resolves to a file in docs/decisions/ (or its archive/).\n'
            '#\n'
            '# Seeded at 2026-10-05 with the pre-existing set, so the gate starts green\n'
            '# and every future dangling reference is a hard failure. Entries here are\n'
            '# accepted debt, not permission to ignore them: each one should eventually\n'
            '# be repointed or removed.\n'
            '#\n'
            '# Regenerate deliberately: python3 scripts/check-adr-references.py --update-baseline\n'
            '\n'
        )
        # Count the rationale that is about to be discarded, before writing rather
        # than after: once the file is rewritten the information is gone.
        baseline_file = pathlib.Path(baseline)
        rationale_before = (
            len([l for l in baseline_file.read_text().splitlines() if l.startswith('#')])
            if baseline_file.exists() else 0
        )
        baseline_file.write_text(header + '\n'.join(dangling) + ('\n' if dangling else ''))
        click.echo(f'check_adr_references: wrote {len(dangling)} entr(ies) to {baseline}')
        # The file is rewritten wholesale, so rationale comments — the recorded reason
        # a piece of debt was accepted — do not survive. Reported rather than
        # mentioned in a comment, because the whole point is that it happens when
        # nobody is reading the source.
        dropped = rationale_before - len(header.splitlines())
        if dropped > 0:
            click.echo(
                f'check_adr_references: warning — {dropped} rationale comment(s) above '
                f'baseline entries were discarded by the rewrite. Re-add the reasons '
                f'that still hold, or accept the entries without them knowingly.'
            )
        # Fall through rather than return. This is the one command that rewrites the
        # baseline, so it is the one place a malformed write lands unnoticed: a
        # `--update-baseline` that then reports success is a gate switched off by its
        # own maintenance path. The verification below must pass on what was written.

    baseline_path = pathlib.Path(baseline)
    accepted: set[str] = set()
    if baseline_path.exists():
        accepted = {l.strip() for l in baseline_path.read_text().splitlines()
                    if l.strip() and not l.startswith('#')}

    new = [d for d in dangling if d not in accepted]
    stale = sorted(accepted - set(dangling))

    for entry in new:
        click.echo(f'ERROR: dangling ADR reference — {entry}')

    if stale:
        click.echo('')
        click.echo(
            f'check_adr_references: {len(stale)} baseline entr(ies) no longer occur; '
            'remove them with --update-baseline'
        )

    if new:
        click.echo('')
        click.echo(
            f'check_adr_references.py: {len(new)} dangling ADR reference(s) '
            f'({len(dangling) - len(new)} baselined)'
        )
        click.echo(
            'Fix: repoint the reference at the current slug, or drop it. If it is a '
            'legitimate exception, add the exact "<file>:<token>" line to '
            f'{baseline_path.relative_to(ROOT)}.'
        )
        raise ctx.exit(VALIDATION_FAILURE)

    click.echo(
        f'check_adr_references.py: OK — {len(slugs)} ADR slugs, '
        f'{len(dangling) - len(stale)} baselined reference(s), 0 new'
    )
    raise ctx.exit(CLEAN)




if __name__ == '__main__':
    raise SystemExit(run(cli))
