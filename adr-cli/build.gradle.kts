// ---------------------------------------------------------------------------
// Build provenance — what `singularity-adr version` reports.
//
// A local binary answers questions about the ADR corpus. Which corpus it was
// built from is a separate question, and mtime cannot answer it: a binary is
// "fresh" whenever its launcher script was rewritten, and the launcher is
// rewritten by builds that changed nothing it reads. The same argument
// `androidApp/build.gradle.kts` makes for versionName, for the same reason —
// a green run is only evidence about the thing that actually ran.
//
// So the sha is baked in. Two deliberate details, both copied from androidApp:
//
//  * `providers.exec`, not a bare `git` call at configuration time. The
//    configuration cache snapshots the filesystem, so a sha read while
//    configuring goes stale exactly when the commit changes — which is the
//    one moment it matters.
//  * A missing git (source tarball, CI export) yields "unknown" rather than
//    failing the build. `version --check` then compares "unknown" with
//    "unknown" and passes, which is the honest answer: nothing is claiming to
//    know which commit this is.
//
// `dirty` covers only the three ADR modules. The rest of the tree cannot
// change what this binary does, and reporting the whole worktree would make
// every unrelated edit look like a different build.
// ---------------------------------------------------------------------------
val adrGitSha: Provider<String> = providers.exec {
    commandLine("git", "rev-parse", "--short=12", "HEAD")
}.standardOutput.asText.map { it.trim() }.orElse("unknown")

val adrGitDirty: Provider<String> = providers.exec {
    commandLine("git", "status", "--porcelain", "--", "adr-cli", "adr-core", "core-base")
}.standardOutput.asText.map { if (it.isBlank()) "clean" else "dirty" }.orElse("unknown")

// A directory, not a file. `resources.srcDir(task)` registers the task's
// output as a *source directory*, and Gradle rejects it outright — "is not a
// directory". The dependency is declared explicitly rather than inferred,
// because the wiring between "this directory" and "that task" is not something
// srcDir can see.
val adrProvenanceDir = layout.buildDirectory.dir("generated/adr-provenance")

val generateAdrProvenance = tasks.register("generateAdrProvenance") {
    val outputDir = adrProvenanceDir
    val sha = adrGitSha
    val dirty = adrGitDirty
    outputs.dir(outputDir)
    inputs.property("sha", sha)
    inputs.property("dirty", dirty)
    doLast {
        // `.get()`, not `toString()`. Interpolating the Provider prints its own
        // internal representation — `or(map(map(map(valueof(...)))), fixed(unknown))`
        // — which lands in the properties file and reads back as a sha that
        // matches nothing. Every value crossing into the generated file is
        // resolved here, at execution time.
        val resolvedSha = sha.get()
        val resolvedDirty = dirty.get()
        val target = outputDir.get().asFile
        target.mkdirs()
        target.resolve("adr-provenance.properties").writeText(
            buildString {
                appendLine("# Generated by :adr-cli:generateAdrProvenance. Do not edit.")
                appendLine("gitSha=$resolvedSha")
                appendLine("gitDirty=$resolvedDirty")
                appendLine("builtFrom=$resolvedSha")
            },
        )
    }
}

sourceSets.named("main") {
    resources.srcDir(adrProvenanceDir)
}

tasks.named<ProcessResources>("processResources") {
    dependsOn(generateAdrProvenance)
}

/**
 * Compose Multiplatform pulls `savedstate-compose-desktop` onto the runtime classpath
 * by two routes, and Gradle refuses to copy a distribution that lists the same jar
 * twice. One copy is the correct outcome either way — this is not a way of hiding a
 * real version conflict, it is two paths to one artefact.
 */
distributions {
    main {
        contents {
            duplicatesStrategy = DuplicatesStrategy.EXCLUDE
        }
    }
}

/**
 * Deliberately no Koin, no Compose, no Room.
 *
 * The CLI's entire dependency surface used to be the desktop app, which meant that
 * `adr list` booted a Swing application and resolved a database graph to read 566
 * markdown files — and, because `user.dir` under Gradle is the daemon's directory, put
 * the results in `~/.singularity-todo` where they are real but not in git (#522).
 *
 * `AdrStorage` takes its three dependencies as constructor parameters precisely so
 * that this module can hand them over directly and skip the container.
 */
dependencies {
    // `:adr-core`, NOT `:shared`. That single edge is what this build file exists to
    // enforce: `:shared` brings Compose Material3, `material-icons-extended`, Room,
    // SQLite, Koin and Koog, so depending on it made `singularity-adr list` ship 127 MB
    // and start in 0.30 s to read markdown files.
    //
    // If a subcommand ever needs something from `:shared`, that is the signal the
    // thing belongs in `:adr-core` — or that it is not an ADR operation at all.
    implementation(project(":adr-core"))
    implementation(libs.kotlinx.datetime)
    // The --json contract (#524) is kotlinx-serialization for the same reason the MCP
    // tools are: the shapes are declared once and encoded, never assembled by hand into
    // a string. `shared` declares this as `implementation`, so it is not transitive.
    implementation(libs.kotlinx.serialization.json)

    testImplementation(libs.kotlin.test.junit5)
    testImplementation(libs.junit.jupiter)
    testImplementation(libs.junit.jupiter.params)
}

